# Simple Interest program

# Input
p = 1000000 # principal Amount
R = 12      # Rate of Interest (%)
T = 15      # Time (years)


# calculation simple interest 
SI = (p * R * T) / 100


# Display Result 
print('pricipal Amount =',p)
print('Rate of Interest =',R,"%")
print('Time  =',T,"Year" )
print('Simple Interest  =',SI)
